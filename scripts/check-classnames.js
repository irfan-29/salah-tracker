// Fails the build when a React component uses a className that neither the app
// stylesheet nor Bootstrap defines.
//
// The React port has now produced this bug four separate times, each shipping:
//
//   tg-module-row   settings.ejs used .tg-row.tg-row-module; the port invented
//                   a parallel name, so the whole Telegram block rendered
//                   unstyled - no row layout, no custom checkbox, no text.
//   form-floating    used across the auth screens, but the React entry point
//                    never loaded Bootstrap, so every one was inert.
//   [missing Bootstrap link]  covered above.
//   (plus a parallel class set in the first Navbar, noted in that file)
//
// The root cause is always the same: the stylesheet and the markup are two
// halves of one thing, and nothing checked that the halves still fit. Porting
// class names by hand has no compiler behind it.
//
// This closes that gap for class names. It cannot prove a class is used in the
// right PLACE or with the right nesting - only that the name exists somewhere.
// A wrong-but-real class still renders wrong; it just renders less obviously
// broken.
//
// Bootstrap's class list lives in bootstrap-classes.txt (21KB, regenerated by
// scripts/refresh-bootstrap-classes.js) rather than vendoring 194KB of CSS.

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const SRC = path.join(ROOT, "frontend", "src");
const BOOTSTRAP_CLASSES = path.join(__dirname, "bootstrap-classes.txt");

// All three stylesheets the React app actually loads. shell.css was missed on
// the first run and produced 4 false positives - the loader's BEM children, the
// surah list and the two status banners are all defined there.
const STYLE_FILES = [
  path.join(ROOT, "public", "css", "styles.css"),
  path.join(ROOT, "frontend", "src", "styles", "base.css"),
  path.join(ROOT, "frontend", "src", "styles", "shell.css"),
];

// Class names that are ours at runtime and legitimately have no CSS rule:
// state/utility hooks used by JS, and third-party names we inject ourselves.
const ALLOW = new Set([
  "active", "selected", "open", "hidden", "visible", "checked", "disabled",
  "loading", "busy", "error", "success", "valid", "invalid", "show", "hide",
  "muted", "row-active", "is-open", "has-error", "react", "root",
  // Set by the audio player / share handler as state hooks.
  "playing", "paused", "shared", "copied", "expanded", "collapsed",
]);

function cssClasses(file) {
  const css = fs.readFileSync(file, "utf8");
  const set = new Set();
  // Strip comments first: a commented-out rule is not a live selector.
  const live = css.replace(/\/\*[\s\S]*?\*\//g, "");
  for (const m of live.matchAll(/\.(-?[_A-Za-z][\w-]*)/g)) set.add(m[1]);
  return set;
}

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) walk(full, out);
    else if (/\.jsx?$/.test(e.name)) out.push(full);
  }
  return out;
}

// Every className in the file: string literals, plus ternaries and template
// concatenations, so `cls={x ? "a" : "b"}` and cls={`a ${b}`} are both seen.
function usedClasses(source) {
  const names = new Map(); // name -> first line
  const push = (raw) => {
    raw.split(/\s+/).forEach((token) => {
      const name = token.replace(/^["'`.]+/, "").trim();
      if (!name || !/^[_A-Za-z][\w-]*$/.test(name)) return;
      if (!names.has(name)) {
        names.set(name, source.slice(0, source.indexOf(raw)).split("\n").length);
      }
    });
  };
  // className="..." and class="..."
  for (const m of source.matchAll(/class(?:Name)?\s*=\s*(["'`])([^"'`]*)\1/g)) push(m[2]);
  // className={"a b"} / className={'a b'}
  for (const m of source.matchAll(/class(?:Name)?\s*=\s*\{\s*(["'`])([^"'`]*)\1\s*\}/g)) push(m[2]);
  return names;
}

// Classes the server-rendered pages used. If a template applied a name and the
// page looked right, the name is a legitimate structural hook even when no rule
// targets it - options-list, language-group and ayah-block are all like this.
// Deriving the allowlist from the templates beats a hand-maintained list,
// because it stays correct as the templates change.
//
// The templates are GONE now (the backend is API-only), so this reads a snapshot
// taken from them at the last commit that still had views/. Regenerate with:
//
//   node scripts/snapshot-template-classes.js <ref>
//
// A class is only reported when it appears in NEITHER a stylesheet NOR this
// list. That combination means it was invented during the port, which is
// exactly the tg-module-row failure.
function templateClasses() {
  const file = path.join(__dirname, "template-classes.txt");
  if (!fs.existsSync(file)) {
    console.error("Missing scripts/template-classes.txt");
    process.exit(1);
  }
  const names = new Set();
  for (const line of fs.readFileSync(file, "utf8").split("\n")) {
    if (line.trim()) names.add(line.trim());
  }
  return names;
}

const known = new Set();
for (const file of STYLE_FILES) {
  if (!fs.existsSync(file)) {
    console.error(`Missing stylesheet: ${path.relative(ROOT, file)}`);
    process.exit(1);
  }
  for (const c of cssClasses(file)) known.add(c);
}
for (const line of fs.readFileSync(BOOTSTRAP_CLASSES, "utf8").split("\n")) {
  if (line.trim()) known.add(line.trim());
}
for (const c of templateClasses()) known.add(c);

const unknown = [];

for (const file of walk(SRC)) {
  const source = fs.readFileSync(file, "utf8");
  const rel = path.relative(ROOT, file);
  for (const [name, line] of usedClasses(source)) {
    if (known.has(name) || ALLOW.has(name)) continue;
    unknown.push({ rel, line, name });
  }
}

if (unknown.length) {
  console.error("className(s) with no matching CSS rule:\n");
  for (const u of unknown) console.error(`  ${u.rel}:${u.line}  ${u.name}`);
  console.error(
    "\nEither the class does not exist (check git history for the name the\n" +
    "server-rendered page used, or scripts/template-classes.txt) or the markup\n" +
    "needs restructuring."
  );
  process.exit(1);
}

console.log("classNames OK.");